"""`--live-audit`: stale `NOT WIRED` tags and undisclosed inert ports.
"""

from pathlib import Path


# Anchor classes. Every anchor lands in exactly one; `anchor_class` is the one
# place the partition is defined, so the report sections and the summary
# counts cannot disagree about where a row went.
LIVE = "live"
STALE = "stale"
TAGGED_PERMISSIVE_ONLY = "tagged-permissive-only"
DISCLOSED = "disclosed"
REPLACED = "replaced"
UNDISCLOSED = "undisclosed"


def anchor_class(a: dict) -> str:
    """The one audit class an anchor belongs to.

    A tagged anchor is read against BOTH graphs. Strict-live means the tag is
    stale (or the strict graph invented an edge); permissive-dead means the
    disclosure is confirmed. The third case - permissive-live, strict-dead - is
    the graphs disagreeing, and it has its own class: before it did, a tagged
    anchor in that state passed every section's filter test by failing it, and
    vanished from the report and from the summary's anchor counts alike.
    """
    tagged = bool(a["not_wired_tag"] or a["replaced_tag"])
    if not tagged:
        return LIVE if a["live"] else UNDISCLOSED
    if a["live_strict"]:
        return STALE
    if a["live"]:
        return TAGGED_PERMISSIVE_ONLY
    # `collect_port_anchors` already resolved precedence, so the two tags are
    # exclusive here.
    return REPLACED if a["replaced_tag"] else DISCLOSED


def render_live_audit(rows: list[dict], out_path: Path | None) -> str:
    """The `--live-audit` report: every ported address that is not reachable.

    Three sections, in the order they need acting on:

    1. **Tagged `NOT WIRED` / `REPLACED-BY` but analysed live** - either the tag
       is stale or the call graph invented an edge. Each row needs a human
       decision, so this section comes first.
    2. **Undisclosed inert ports** - not reachable, no tag. The disclosure gap.
    3. **Disclosed inert ports** - not reachable, `NOT WIRED:` present. Working
       as intended; listed so the wiring worklist is complete.
    4. **Infra-replaced ports** - not reachable, `REPLACED-BY:` present. Not a
       wiring worklist at all; listed with the mechanism each names so the
       exemption can be argued with.
    """
    # A `NOT WIRED:` tag is written per *anchor*, so the audit has to compare
    # per anchor. Rolling up to the address first hides the case where an
    # address is ported twice, one copy wired and one not - which is the
    # normal shape for a formula shared between `engine-vm` and `engine-core`.
    pairs = [
        (r, a) for r in rows if r["ported"] and r["live_known"] for a in r["anchors"]
    ]
    by_class: dict[str, list[tuple[dict, dict]]] = {}
    for r, a in pairs:
        by_class.setdefault(anchor_class(a), []).append((r, a))
    stale = by_class.get(STALE, [])
    undisclosed = by_class.get(UNDISCLOSED, [])
    disclosed = by_class.get(DISCLOSED, [])
    replaced = by_class.get(REPLACED, [])
    permissive_only = by_class.get(TAGGED_PERMISSIVE_ONLY, [])

    def table(
        title: str,
        subset: list[tuple[dict, dict]],
        note: str,
        mechanism: bool = False,
    ) -> list[str]:
        out = [f"## {title} ({len(subset)})", "", note, ""]
        if not subset:
            out += ["None.", ""]
            return out
        head = ["addr", "crate", "anchor", "symbol", "site"]
        if mechanism:
            head.append("replaced by")
        out += [
            "| " + " | ".join(head) + " |",
            "|" + "---|" * len(head),
        ]
        for r, a in sorted(subset, key=lambda ra: (ra[0]["addr"], ra[1]["file"])):
            row = (
                f"| `{r['addr']}` | {a['crate']} | {a['kind']} | "
                f"`{a['symbol']}` | `{a['file']}:{a['line']}` |"
            )
            if mechanism:
                # The mechanism is prose from the source. Print its first
                # sentence: that is the claim, and the paragraph that follows
                # it belongs at the file:line the row already names.
                text = " ".join(a.get("replaced_by", "").split())
                if not text and a.get("not_wired_tag"):
                    # A mixed section: a `NOT WIRED:` row names no mechanism,
                    # and an empty cell would read as a bare `REPLACED-BY:`.
                    text = "(`NOT WIRED:` - no replacement claimed)"
                cut = text.find(". ")
                if cut > 0:
                    text = text[: cut + 1]
                row += f" {text[:220]} |"
            out.append(row)
        out.append("")
        return out

    lines = [
        "# Live-reachability audit",
        "",
        "Generated by `scripts/ci/port-catalog.py --live-audit`. `live` means the "
        "Rust symbol carrying the `// PORT:` tag is reachable through non-test "
        "code from a declared host entry point - see "
        "[`docs/tooling/port-catalog.md`](../../docs/tooling/port-catalog.md) for "
        "the root set and the analysis's known false negatives.",
        "",
    ]
    quoted = sum(1 for _r, a in stale if a.get("quoted_marker_only"))
    note = (
        "Either the tag is stale (the port got wired since) or the call graph "
        "resolved a name-collision edge that does not exist. Check by hand."
    )
    if quoted:
        note += (
            f" **{quoted} of these carr{'ies' if quoted == 1 else 'y'} no marker "
            "at all**: every `NOT WIRED` "
            "in the anchor's doc block is quoted, so the block is describing "
            "the marker rather than carrying one - usually a wiring note that "
            "recounts the disclosure it replaced. The per-item search is "
            "deliberately unanchored (the spellings a real disclosure uses are "
            "too varied to anchor), so the fix is in the prose: rewrite, never "
            "quote the marker text."
        )
    lines += table(
        "Tagged `NOT WIRED` / `REPLACED-BY` but analysed live",
        stale,
        note,
    )
    lines += table(
        "Undisclosed inert ports",
        undisclosed,
        "Not reachable from any host root and carrying no `NOT WIRED:` tag. "
        "Each is either a wiring gap or a missing disclosure.",
    )
    lines += table(
        "Disclosed inert ports",
        disclosed,
        "Not reachable, and the source says so. The declared wiring worklist.",
    )
    lines += table(
        "Tagged, live only on the permissive graph",
        permissive_only,
        "Carrying a `NOT WIRED:` or `REPLACED-BY:` tag, reachable on the "
        "permissive graph and inert on the receiver-gated one. The two graphs "
        "disagree, so the audit can neither confirm the disclosure nor call it "
        "stale: the permissive edge is usually a name collision, and the row "
        "is a disclosed gap (or a replacement) until a reader shows otherwise. "
        "Without this section these anchors fell into no class at all - not "
        "inert, so absent from the worklist; not strict-live, so absent from "
        "the stale list.",
        mechanism=True,
    )
    lines += table(
        "Infra-replaced ports",
        replaced,
        "Not reachable, and no host is owed: the routine's job is done in the "
        "port by the named mechanism, so these are excluded from the wiring "
        "denominator rather than counted as gaps. See "
        "[`port-catalog.md`](../../docs/tooling/port-catalog.md#replaced-by) "
        "for what may carry the tag.",
        mechanism=True,
    )
    md = "\n".join(lines) + "\n"
    if out_path:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(md)
    return md
