# Public-domain dedications: nothing to reproduce, so a crate under one of
# these needs no text (it is still listed).
NO_NOTICE = {"CC0-1.0", "0BSD"}

# Which file names identify which SPDX id, for borrowing a text across crates.
ID_HINTS = {
    "Apache-2.0": re.compile(r"apache", re.I),
    "MIT": re.compile(r"\bmit\b|license-mit|licence-mit", re.I),
    "BSL-1.0": re.compile(r"boost|bsl", re.I),
    "Zlib": re.compile(r"zlib", re.I),
    "Unicode-3.0": re.compile(r"unicode", re.I),
    "OFL-1.1": re.compile(r"ofl", re.I),
    "Ubuntu-font-1.0": re.compile(r"ufl|ubuntu", re.I),
    "BSD-3-Clause": re.compile(r"bsd|whatwg", re.I),
    "Unlicense": re.compile(r"unlicense", re.I),
}


def parse_spdx(expr: str):
    """Parse an SPDX expression into nested tuples: ("or", [..]),
    ("and", [..]) or ("id", name). `WITH <exception>` keeps the base id; the
    legacy `/` separator reads as OR."""
    toks = re.findall(r"\(|\)|[^\s()/]+|/", expr or "")
    toks = ["OR" if t == "/" else t for t in toks]
    pos = 0

    def peek():
        return toks[pos] if pos < len(toks) else None

    def factor():
        nonlocal pos
        t = peek()
        if t == "(":
            pos += 1
            node = disj()
            if peek() == ")":
                pos += 1
            return node
        pos += 1
        if peek() == "WITH":
            pos += 2
        return ("id", t)

    def conj():
        nonlocal pos
        parts = [factor()]
        while peek() == "AND":
            pos += 1
            parts.append(factor())
        return parts[0] if len(parts) == 1 else ("and", parts)

    def disj():
        nonlocal pos
        parts = [conj()]
        while peek() == "OR":
            pos += 1
            parts.append(conj())
        return parts[0] if len(parts) == 1 else ("or", parts)

    return disj() if toks else None


def spdx_ids(expr: str) -> list[str]:
    """The license ids an SPDX expression names (operators and parens dropped;
    the legacy `/` separator counts as OR)."""
    ids = re.split(r"[\s()/]+|\bOR\b|\bAND\b|\bWITH\b", expr or "")
    return sorted({i for i in ids if i and i not in ("OR", "AND", "WITH")})


def metadata(triple: str, manifest: Path | None) -> dict:
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", triple]
    if manifest:
        cmd += ["--manifest-path", str(manifest)]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def shipped_packages(meta: dict, triple: str, manifest: Path | None) -> set[str]:
    """Package ids reachable from the workspace's binary-building members over
    normal dependency edges, as the release build resolves them.

    `cargo metadata`'s own resolve lists optional dependencies no enabled
    feature turns on (eframe's unused wgpu backend, for one), so the set comes
    from `cargo tree --workspace -e normal`, which resolves features exactly
    as `cargo build --workspace` does; metadata then supplies each package's
    manifest path and license fields."""
    by_id = {p["id"]: p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    bin_members = {
        (by_id[pid]["name"], by_id[pid]["version"])
        for pid in members
        if any("bin" in t["kind"] for t in by_id[pid]["targets"])
    }
    by_name_ver = {}
    for pid, pkg in by_id.items():
        if pid not in members:
            by_name_ver.setdefault((pkg["name"], pkg["version"]), pid)
    cmd = [
        "cargo", "tree", "--workspace", "-e", "normal", "--target", triple,
        "--prefix", "depth", "--format", "{p}", "--locked",
    ]
    if manifest:
        cmd += ["--manifest-path", str(manifest)]
    tree = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    line_re = re.compile(r"^(\d+)(\S+) v(\S+)")
    out: set[str] = set()
    in_shipped_root = False
    for line in tree.splitlines():
        m = line_re.match(line)
        if not m:
            continue
        depth, name, ver = int(m.group(1)), m.group(2), m.group(3)
        if depth == 0:
            in_shipped_root = (name, ver) in bin_members
            continue
        if in_shipped_root and (name, ver) in by_name_ver:
            out.add(by_name_ver[(name, ver)])
    return out


def license_files(pkg: dict) -> list[Path]:
    root = Path(pkg["manifest_path"]).parent
    files: list[Path] = []
    for f in sorted(root.iterdir()):
        if f.is_file() and ROOT_NAME.match(f.name):
            files.append(f)
    if pkg.get("license_file"):
        lf = (root / pkg["license_file"]).resolve()
        if lf.is_file() and lf not in files:
            files.append(lf)
    # Notices below the root (font licenses next to their fonts, ...).
    for sub in sorted(p for p in root.iterdir() if p.is_dir() and p.name.lower() not in SKIP_DIRS):
        for f in sorted(sub.rglob("*")):
            if not f.is_file() or len(f.relative_to(root).parts) > 3:
                continue
            if any(part.lower() in SKIP_DIRS for part in f.relative_to(root).parts[:-1]):
                continue
            font_pair = f.suffix.lower() == ".txt" and any(
                (f.with_suffix(ext)).exists() for ext in FONT_EXT
            )
            if (SUB_NAME.search(f.name) and f.suffix.lower() in {"", ".txt", ".md"}) or font_pair:
                files.append(f)
    return files


def read_text(f: Path) -> str:
    return f.read_text(encoding="utf-8", errors="replace").strip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--target", action="append", required=True, help="rustc target triple (repeatable)")
    ap.add_argument("--manifest-path", type=Path)
    ap.add_argument("--out", type=Path, help="write here instead of stdout")
    ap.add_argument("-v", "--verbose", action="store_true", help="list the borrowed texts")
    args = ap.parse_args()

    pkgs: dict[str, dict] = {}
    for triple in args.target:
        meta = metadata(triple, args.manifest_path)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pid in shipped_packages(meta, triple, args.manifest_path):
            pkgs[pid] = by_id[pid]

    problems: list[str] = []
    # name@version -> list of (file label, text)
    texts: dict[str, list[tuple[str, str]]] = {}
    ids_of: dict[str, list[str]] = {}
    for pid, p in sorted(pkgs.items(), key=lambda kv: (kv[1]["name"], kv[1]["version"])):
        key = f'{p["name"]} {p["version"]}'
        expr = p.get("license") or ""
        if not expr and not p.get("license_file"):
            problems.append(f"{key}: declares no license")
        ids_of[key] = spdx_ids(expr)
        texts[key] = [(f.name, read_text(f)) for f in license_files(p)]

    # Borrowable text per SPDX id: the most common text among files whose
    # name hints that id, across every shipped crate.
    pool: dict[str, dict[str, int]] = {}
    for key, files in texts.items():
        for name, body in files:
            for spdx, hint in ID_HINTS.items():
                if hint.search(name) or (spdx == "Apache-2.0" and "Apache License" in body[:200]):
                    pool.setdefault(spdx, {}).setdefault(body, 0)
                    pool[spdx][body] += 1

    def fallback(spdx: str) -> str | None:
        cands = pool.get(spdx)
        if cands:
            return max(cands.items(), key=lambda kv: kv[1])[0]
        return CANONICAL.get(spdx)

    # Which texts a crate must carry. An OR is satisfied by one branch, so a
    # branch the crate ships text for wins and nothing is borrowed; an AND
    # needs every part. A borrowed text prefers wording with no copyright
    # holder in it (the Apache-2.0 text, the canonical templates) so no
    # crate is credited with another crate's copyright line.
    BORROW_ORDER = ["Apache-2.0", "MIT", "BSL-1.0", "Zlib", "Unlicense"]

    def own(spdx: str, files: list[tuple[str, str]]) -> bool:
        hint = ID_HINTS.get(spdx)
        if spdx in NO_NOTICE:
            return True
        if hint is None:
            return bool(files)
        return any(hint.search(n) for n, _ in files) or (
            spdx == "Apache-2.0" and any("Apache License" in b[:200] for _, b in files)
        )

    def borrow_text(spdx: str) -> str | None:
        if spdx in CANONICAL:
            return CANONICAL[spdx]
        return fallback(spdx)

    def plan(node, files, unhinted_ok):
        """Returns (ids to borrow, satisfiable)."""
        kind, val = node
        if kind == "id":
            if own(val, files) or unhinted_ok:
                return [], True
            return ([val], True) if borrow_text(val) is not None else ([val], False)
        if kind == "and":
            need, ok = [], True
            for part in val:
                n, o = plan(part, files, unhinted_ok)
                need += n
                ok = ok and o
            return need, ok
        # "or": a branch with nothing to borrow, else the most borrowable one.
        options = [plan(part, files, unhinted_ok) for part in val]
        for n, o in options:
            if o and not n:
                return n, o

        def rank(opt):
            n, _ = opt
            return min((BORROW_ORDER.index(i) if i in BORROW_ORDER else 99) for i in n)

        good = [o for o in options if o[1]]
        return (min(good, key=rank) if good else options[0])

    groups: dict[str, dict] = {}
    borrowed: list[str] = []
    for key, files in texts.items():
        bodies = [b for _, b in files]
        covered = " ".join(n for n, _ in files)
        p = next(v for v in pkgs.values() if f'{v["name"]} {v["version"]}' == key)
        tree = parse_spdx(p.get("license") or "")
        # Files that name no license at all ("LICENSE", "COPYING") are the
        # author's own notice for the whole expression.
        hinted = any(any(h.search(n) for h in ID_HINTS.values()) for n, _ in files)
        unhinted_ok = bool(files) and not hinted
        if tree is not None:
            need, ok = plan(tree, files, unhinted_ok)
            for spdx in need:
                text = borrow_text(spdx)
                if text is None:
                    problems.append(f"{key}: no text available for {spdx} (files: {covered or 'none'})")
                    continue
                bodies.append(text)
                borrowed.append(f"{key} ({spdx})")
        for b in bodies:
            h = hashlib.sha256(b.encode()).hexdigest()
            g = groups.setdefault(h, {"text": b, "crates": set()})
            g["crates"].add(key)

    out = []
    out.append("THIRD-PARTY SOFTWARE NOTICES AND LICENSES\n")
    out.append("=========================================\n\n")
    out.append(
        "The programs in this archive are licensed MIT OR Unlicense (see LICENSE and\n"
        "LICENSE-MIT). They are built from the following third-party Rust crates,\n"
        "whose licenses and notices follow, each text once with every crate that\n"
        "ships it listed above it.\n\n"
    )
    out.append(f"Targets: {', '.join(args.target)}\n")
    out.append(f"Crates:  {len(pkgs)}\n\n")
    out.append("CRATES\n------\n\n")
    for key in sorted(texts):
        p = next(v for v in pkgs.values() if f'{v["name"]} {v["version"]}' == key)
        repo = p.get("repository") or ""
        out.append(f"{key:<48} {p.get('license') or '(license-file)'}  {repo}\n")
    out.append("\nLICENSE TEXTS\n-------------\n")
    for g in sorted(groups.values(), key=lambda g: (-len(g["crates"]), sorted(g["crates"])[0])):
        out.append("\n" + "=" * 78 + "\n")
        names = sorted(g["crates"])
        out.append("Used by: " + ", ".join(names) + "\n")
        out.append("=" * 78 + "\n\n")
        out.append(g["text"])
    text = "".join(out)

    if args.out:
        args.out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    print(
        f"[third-party-licenses] {len(pkgs)} crates, {len(groups)} distinct texts, "
        f"{len(borrowed)} id(s) filled from another crate or the canonical text",
        file=sys.stderr,
    )
    if args.verbose:
        for b in borrowed:
            print(f"[third-party-licenses] text borrowed for {b}", file=sys.stderr)
    if problems:
        for p in problems:
            print(f"[third-party-licenses] ERROR: {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
