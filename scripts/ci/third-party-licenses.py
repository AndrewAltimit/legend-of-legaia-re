#!/usr/bin/env python3
"""Write THIRD-PARTY-LICENSES.txt for the release archives.

Every binary in a release archive statically links third-party crates, and
most of their licenses (MIT, Apache-2.0, BSL-1.0, Zlib, Unicode-3.0, the
OFL / Ubuntu font licenses of egui's bundled fonts, ...) ask for their notice
to travel with the binary. This collects them from the crates themselves:

1. `cargo metadata --filter-platform <triple>` (once per triple; a universal
   macOS archive passes both slices) gives the resolved, feature-aware
   dependency graph for that target.
2. The shipped set is the closure of every workspace package that builds a
   binary, over **normal** dependency edges only - build scripts and dev
   dependencies do not end up in a shipped executable - read from
   `cargo tree --workspace -e normal --target <triple>`, which resolves
   features the way the release's `cargo build --workspace` does.
3. For each third-party package, the license texts are the files the crate
   ships: `LICENSE*` / `LICENCE*` / `COPYING*` / `NOTICE*` / `COPYRIGHT*` /
   `UNLICENSE` at its root plus the manifest's `license-file`, and below the
   root the files that are plainly license notices (names carrying
   license / licence / OFL / UFL / copying / notice, or a `.txt` sitting next
   to a font of the same stem, which is how font crates ship their terms).
4. A crate that ships no text for an SPDX id in its `license` expression gets
   that id's text from the crates that do ship it (identical wording,
   different crate), or from the short canonical texts below.

Texts are grouped by content, so a license shared by two hundred crates is
printed once with all two hundred listed above it. Exits 1 when a shipped
crate declares no license at all, or when an SPDX id has no text anywhere -
a release must not ship an unaccounted dependency.

    third-party-licenses.py --target aarch64-unknown-linux-gnu > THIRD-PARTY-LICENSES.txt
    third-party-licenses.py --target aarch64-apple-darwin --target x86_64-apple-darwin

Kept to Python 3.8 and the standard library (the macOS runner's python3).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT_NAME = re.compile(r"^(licen[cs]e|copying|notice|copyright|unlicense)", re.I)
SUB_NAME = re.compile(r"(licen[cs]e|copying|notice|\bofl\b|\bufl\b|^ofl|^ufl)", re.I)
FONT_EXT = {".ttf", ".otf", ".woff", ".woff2"}
SKIP_DIRS = {"src", "tests", "benches", "examples", "target", ".git", "test", "testdata"}

