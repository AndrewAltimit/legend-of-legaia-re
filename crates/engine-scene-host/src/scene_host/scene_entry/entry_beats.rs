//! The scene selector's **entry beats**: per picked scene, the story arrival
//! whose walk-on cutscene plays the moment a door lands the party there.
//!
//! A retail door's `0x3F` seats the party on its entry tile, and the field
//! loop's first post-arrival frame compares that tile against stale last-tile
//! globals (`FUN_801D1EC4` -> `FUN_801D5630`): a `.MAP` kind-1 gate-1 trigger
//! there spawns its partition-2 record through `FUN_8003BDE0`, whose C1 / C2
//! story-flag gates decide whether it runs. That spawn is the area's arrival
//! beat - Garmel's welcome, the Rogue's Tower entrance, a dungeon's opening
//! line - the first thing a player who walks in sees.
//!
//! The default picker seat ([`crate::scene_host::SceneHost::arm_picker_entry_seat`]) steps off
//! every gate-1 tile so no beat fires; the play hosts' scene selectors ask
//! [`crate::scene_host::SceneHost::arm_picker_story_entry`] instead, which seats a scene listed in
//! [`PICKER_ENTRY_BEATS`] on its row's arrival so the beat plays on the first
//! tick, and every other scene by the default rule.
//!
//! The rows are generated, not curated: the disc-gated
//! `picker_entry_beats_disc` test walks every selector scene's inbound
//! arrivals in [`ArrivalCatalog::ranked`] order, keeps the arrivals whose
//! entry tile carries a gate-1 trigger on a non-door record, seats a fresh
//! picker visit on each (after the free-roam staging,
//! [`legaia_engine_core::world::World::stage_picker_entry`]) and keeps the
//! first whose record installs on the first tick, plays for a while and hands
//! control back in the scene. Only an overworld entrance or a walk-on door
//! counts as a story entrance: a beat behind a scripted arrival (another
//! scene's cutscene hopping the party in) continues that scene's event. Its output is the block below, and the same
//! test fails when the disc's answer and the block disagree
//! (`LEGAIA_PICKER_BEATS_WRITE=1` rewrites it). Arrival beats the selector
//! cannot stage (a C2 flag it does not seed, a beat that leaves the scene or
//! starts a fight) are listed in [`PICKER_ENTRY_BEATS_HELD`], and those scenes
//! keep the default seat.
//!
//! [`ArrivalCatalog::ranked`]: legaia_engine_scene::scene_arrivals::ArrivalCatalog::ranked
// REF: FUN_801D1EC4, FUN_801D5630, FUN_8003BDE0

/// A scene the selector seats on its arrival beat.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PickerEntryBeat {
    /// The picked scene (CDNAME label).
    pub scene: &'static str,
    /// The scene whose `0x3F` lands the party on the beat's trigger.
    pub from: &'static str,
    /// The `0x3F`'s entry tile (low 7 bits of its entry bytes), the trigger
    /// tile.
    pub tile: (u8, u8),
    /// The arrival's facing sector (`dir & 7`).
    pub dir: u8,
    /// The partition-2 record the trigger spawns.
    pub record: u8,
}

/// Why an arrival beat is not staged by the selector.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HeldReason {
    /// The record's C2 list needs story flags the selector does not seed.
    NeedsFlags(&'static [u16]),
    /// The record's C1 list names a flag the selector's staging holds set
    /// (flag `7`, the MAN loader's, marks developer leftovers).
    BlockedByFlags(&'static [u16]),
    /// The gates pass but the record does not install, or ends at once.
    DoesNotPlay,
    /// The beat ends in a scene change out of the picked scene.
    LeavesScene(&'static str),
    /// The beat starts a battle.
    StartsBattle,
    /// The beat does not hand control back in a headless visit (`town01`'s
    /// gate record is the New Game opening, which runs on into name entry).
    DoesNotEnd,
    /// The beat plays, but its arrival is a scripted scene change (a story
    /// hop out of another scene's cutscene), not a door a player walks
    /// through: the beat continues that other scene's event.
    ScriptedArrival,
}

/// An arrival beat the selector does not stage; the scene keeps its default
/// seat.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PickerEntryBeatHeld {
    /// The picked scene.
    pub scene: &'static str,
    /// The scene whose `0x3F` lands on the trigger.
    pub from: &'static str,
    /// The entry tile.
    pub tile: (u8, u8),
    /// The partition-2 record the trigger spawns.
    pub record: u8,
    /// Why it is held.
    pub reason: HeldReason,
}

/// The [`PICKER_ENTRY_BEATS`] row for `scene`.
pub fn picker_entry_beat(scene: &str) -> Option<&'static PickerEntryBeat> {
    PICKER_ENTRY_BEATS.iter().find(|b| b.scene == scene)
}

