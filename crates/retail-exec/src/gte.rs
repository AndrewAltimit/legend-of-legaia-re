    #[test]
    fn depth_cue_and_general_purpose_interpolation() {
        let mut g = Gte::default();
        g.data[6] = 0x3020_4080;
        g.execute(DPCS);
        assert_eq!(g.read_data(22), 0x3020_4080);
        g.ctrl[21] = 0xFF0;
        g.data[8] = 0x1000;
        g.execute(DPCS);
        assert_eq!(g.read_data(22), 0x3000_00FF);
        assert_eq!(g.read_data(21), 0x3020_4080);

        g.data[8] = 0x800;
        g.data[9] = 0x1000;
        g.data[10] = 0x2000;
        g.data[11] = 0;
        g.execute(GPF_SF);
        assert_eq!([g.read_data(9), g.read_data(10)], [0x800, 0x1000]);
        // G = 0x1000 >> 4 = 0x100 saturates at 0xFF.
        assert_eq!(g.read_data(22), 0x3000_FF80);
        assert_eq!(g.read_ctrl(31), flag::COLOR_R_SAT >> 1);
    }
