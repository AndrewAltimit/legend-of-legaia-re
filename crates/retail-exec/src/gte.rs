    #[test]
    fn register_quirks() {
        let mut g = Gte::default();
        g.write_data(28, 0x7FFF);
        assert_eq!(g.read_data(9), 0xF80);
        assert_eq!(g.read_data(29), 0x7FFF);
        assert_eq!(g.read_data(28), 0x7FFF);
        g.write_data(9, (-5i32) as u32);
        assert_eq!(g.read_data(9), (-5i32) as u32);
        assert_eq!(g.read_data(29) & 0x1F, 0);
        for (v, n) in [
            (0u32, 32),
            (u32::MAX, 32),
            (0xFFFF, 16),
            (0xFFFF_0000, 16),
            (1, 31),
        ] {
            g.write_data(30, v);
            assert_eq!(g.read_data(31), n, "lzcs {v:#x}");
        }
        g.write_data(16, 0xFFFF_8000);
        assert_eq!(g.read_data(16), 0x8000);
        g.write_ctrl(26, 0x8000);
        assert_eq!(g.read_ctrl(26), 0xFFFF_8000);
        g.write_ctrl(31, u32::MAX);
        assert_eq!(g.read_ctrl(31), 0xFFFF_F000);
        g.write_ctrl(31, 1 << 20);
        assert_eq!(g.read_ctrl(31), 1 << 20);
    }

